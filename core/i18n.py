LANG_INDEX = {"en": 0, "ja": 1}


def translator(lang: str) -> Callable[..., str]:
    i = LANG_INDEX.get(lang, 0)

    def t(key: str, **kwargs) -> str:
        pair = TEXTS.get(key)
        text = pair[i] if pair else key
        if kwargs:
            try:
                return text.format(**kwargs)
            except (KeyError, ValueError, IndexError):
                return text
        return text

    return t
